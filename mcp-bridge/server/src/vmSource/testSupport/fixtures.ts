import { promises as fs } from 'node:fs';

// Synthetic builders for upstream-shaped generated C files. Every emitted line form is
// copied from opensmalltalk-vm @ 3ea6bd17fabb5aca6fcbd175185d2fccdd50d919; the comment above
// each emitter cites the upstream line it mirrors. `excerpts/` holds the verbatim originals.

/** One generated C function definition. */
export interface CFunctionSpec {
  name: string;
  generatedFrom?: string;
  returnType?: string;
  args?: string;
  body: string[];
}

/** Rows of a `{(void*)_m, …}` exports array. */
export interface ExportSpec {
  name: string;
  fn?: string;
}

/** Inputs for a synthetic `cointerp.c`. */
export interface CoreInterpSpec {
  version?: string;
  /** VMMaker author initials in `VMMaker.oscog-<author>.<version>`; defaults to `eem`. */
  author?: string;
  family?: string;
  functions?: CFunctionSpec[];
  table?: Record<number, string | number>;
  exports?: ExportSpec[];
  defines?: string[];
  extra?: string[];
}

/** Inputs for a synthetic plugin `.c` file. */
export interface PluginSpec {
  module: string;
  stampVersion?: string;
  stampName?: string;
  exportsName?: string;
  proxyPointers?: string[];
  functions?: CFunctionSpec[];
  exports?: ExportSpec[];
  defines?: string[];
  extra?: string[];
}

// cointerp.c:25864-25867 — "\t/* InterpreterPrimitives>>#primitiveAdd */", "static void",
// "primitiveAdd(void)", "{   DECL_MAYBE_SQ_GLOBAL_STRUCT"; the bare "{" form is
// SocketPlugin.c:1793; the closing column-0 "}" is cointerp.c:25886.
function emitFunction(spec: CFunctionSpec, defaultReturnType: string): string {
  const lines: string[] = [];
  if (spec.generatedFrom !== undefined) lines.push(`\t/* ${spec.generatedFrom} */`);
  lines.push(spec.returnType ?? defaultReturnType);
  lines.push(`${spec.name}(${spec.args ?? 'void'})`);
  lines.push('{');
  lines.push(...spec.body);
  lines.push('}');
  return lines.join('\n');
}

/** Emits one function definition; return type defaults to `static void` (cointerp.c:25865). */
export function cFunction(spec: CFunctionSpec): string {
  return emitFunction(spec, 'static void');
}

// cointerp.c:84253 / SocketPlugin.c:2397 — "\t{(void*)_m, \"name\\000\\377\\000\", (void*)fn},";
// the closing pair is cointerp.c:84340-84341 / SocketPlugin.c:2462-2463.
function emitExportRows(rows: ExportSpec[]): string[] {
  return [
    ...rows.map((r) => `\t{(void*)_m, "${r.name}\\000\\377\\000", (void*)${r.fn ?? r.name}},`),
    '\t{NULL, NULL, NULL}',
    '};',
  ];
}

// cointerp.c:1-6 / SocketPlugin.c:1-6 — the "Automatically generated by" banner.
function emitBanner(generator: string, packages: string, source: string, version: string, author: string): string[] {
  const uuid = 'uuid: 8300897a-5044-4357-bf20-12f9abf85bf3';
  return [
    '/* Automatically generated by',
    `\t${generator} VMMaker.oscog-${author}.${version} ${uuid}`,
    `\t(${packages})`,
    '   from',
    `\t${source} VMMaker.oscog-${author}.${version} ${uuid}`,
    ' */',
  ];
}

/** Builds a full `cointerp.c`-shaped file (ends with '\n'). */
export function coreInterp(spec: CoreInterpSpec = {}): string {
  const version = spec.version ?? '3794';
  const family = spec.family ?? 'Cog[Spur]';
  const author = spec.author ?? 'eem';
  const lines: string[] = [
    ...emitBanner('CCodeGeneratorGlobalStructure', 'Cog-eem.513, Compiler-ct.535', 'CoInterpreter', version, author),
    '',
  ];

  // cointerp.c:2062 opening; rows :2063 "\t/* 0 */ (void (*)(void))0,", :2180
  // "\t/* 117 */ primitiveExternalCall,", :2319 "\t/* 256 */ (void (*)(void))256,"; close :2647 " 0 };".
  lines.push('static void (*primitiveTable[MaxPrimitiveIndex + 2 /* 585 */])(void) = {');
  const slots = Object.keys(spec.table ?? {}).map(Number).sort((a, b) => a - b);
  for (const n of slots) {
    const v = spec.table![n];
    lines.push(typeof v === 'number' ? `\t/* ${n} */ (void (*)(void))${v},` : `\t/* ${n} */ ${v},`);
  }
  lines.push(' 0 };');

  // cointerp.c:2737
  lines.push(
    `const char *interpreterVersion = "Open Smalltalk ${family} VM [CoInterpreterPrimitives VMMaker.oscog-${author}.${version}]";`,
  );

  // cointerp.c:2751 "/*** Macros ***/", :2756 "#define mostRecentlyUsedPage() GIV(mostRecentlyUsedPage)"
  lines.push('', '/*** Macros ***/', ...(spec.defines ?? []), '', '');

  // cointerp.c:2864
  lines.push('/*** Methods ***/');
  for (const f of spec.functions ?? []) lines.push(emitFunction(f, 'static void'), '');

  // cointerp.c:84249-84252
  lines.push('', '/*** Exports ***/', '', 'static char _m[] = "";', 'void* vm_exports[][3] = {');
  lines.push(...emitExportRows(spec.exports ?? []));

  lines.push(...(spec.extra ?? []));
  return lines.join('\n') + '\n';
}

/** Builds a full plugin `.c`-shaped file (ends with '\n'). */
export function plugin(spec: PluginSpec): string {
  const stampVersion = spec.stampVersion ?? '3743';
  const stampName = spec.stampName ?? spec.module;
  const exportsName = spec.exportsName ?? `${stampName}_exports`;
  const pointers = spec.proxyPointers ?? [];
  const lines: string[] = [...emitBanner('SmartSyntaxPluginCodeGenerator', 'Compiler-ct.530', stampName, stampVersion, 'eem'), ''];

  // SocketPlugin.c:109-111 "/*** Variables ***/", "#if !defined(SQUEAK_BUILTIN_PLUGIN)";
  // :122 "static sqInt (*failed)(void);"; :157 "#else /* !defined(SQUEAK_BUILTIN_PLUGIN) */";
  // :202 "extern sqInt trueObject(void);"; :204 "#endif"; :205-206 interpreterProxy, moduleName.
  lines.push('/*** Variables ***/', '', '#if !defined(SQUEAK_BUILTIN_PLUGIN)');
  for (const p of pointers) lines.push(`static sqInt (*${p})(void);`);
  lines.push('#else /* !defined(SQUEAK_BUILTIN_PLUGIN) */');
  for (const p of pointers) lines.push(`extern sqInt ${p}(void);`);
  lines.push('#endif');
  lines.push('struct VirtualMachine* interpreterProxy;');
  lines.push(`static const char *moduleName = "${stampName} VMMaker.oscog-eem.${stampVersion} " INT_EXT;`);
  lines.push(...(spec.defines ?? []), '', '');

  // SocketPlugin.c:214; functions as SocketPlugin.c:1790-1817 (return type "EXPORT(sqInt)").
  lines.push('/*** Methods ***/');
  for (const f of spec.functions ?? []) lines.push(emitFunction(f, 'EXPORT(sqInt)'), '');

  // SocketPlugin.c:2389-2394; ARM64AppleFFIPlugin.c:5058-5059 ("_m" is the module, the
  // array is named after the stamp); trailers as SocketPlugin.c:2465 and :2516.
  lines.push('', '/*** Exports ***/', '', '#ifdef SQUEAK_BUILTIN_PLUGIN', '');
  lines.push(`static char _m[] = "${spec.module}";`, `void* ${exportsName}[][3] = {`);
  lines.push(...emitExportRows(spec.exports ?? []));
  lines.push('', '#else // ifdef SQ_BUILTIN_PLUGIN', '', '#endif // ifdef SQ_BUILTIN_PLUGIN');

  lines.push(...(spec.extra ?? []));
  return lines.join('\n') + '\n';
}

/** Reads `excerpts/<name>` and drops its `// excerpt:` header lines. */
export async function readExcerpt(name: string): Promise<string> {
  const text = await fs.readFile(new URL(`./excerpts/${name}`, import.meta.url), 'utf8');
  return text
    .split('\n')
    .filter((l) => !l.startsWith('// excerpt:'))
    .join('\n');
}
